/// Exercise actual macOS font selection, including GPUI's metrics-glyph guard.
/// Merely accepting add_fonts() does not prove that the family can be selected.
pub fn verify_native(text: &gpui::TextSystem) -> anyhow::Result<()> {
    let id = text.resolve_font(&gpui::font("bootstrap-icons"));
    anyhow::ensure!(
        text.get_font_for_id(id)
            .is_some_and(|f| f.family.as_ref() == "bootstrap-icons"),
        "图标字体被系统回退字体替代"
    );
    anyhow::ensure!(
        text.em_width(id, gpui::px(16.))? > gpui::px(0.),
        "图标字体缺少度量字符"
    );
    for name in [
        "journal-text",
        "plus-lg",
        "cloud",
        "arrow-repeat",
        "arrow-down-circle-fill",
        "file-earmark-text",
        "layout-sidebar",
        "arrows-fullscreen",
        "trash3",
        "code-slash",
        "file-diff",
        "table",
    ] {
        let glyph = glyph(name);
        anyhow::ensure!(glyph != "?", "未定义图标：{name}");
        let bounds = text.typographic_bounds(id, gpui::px(16.), glyph.chars().next().unwrap())?;
        anyhow::ensure!(
            bounds.size.width > gpui::px(0.) && bounds.size.height > gpui::px(0.),
            "图标没有可绘制轮廓：{name}"
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn embedded_font_contains_gpui_metrics_and_every_native_icon() {
        let face =
            ttf_parser::Face::parse(include_bytes!("../assets/bootstrap-icons.ttf"), 0).unwrap();
        // GPUI's macOS loader skips the whole family when 'm' is missing.
        let m = face
            .glyph_index('m')
            .expect("GPUI requires a metrics m glyph");
        assert!(face.glyph_bounding_box(m).unwrap().width() > 0);
        for name in [
            "journal-text",
            "plus-lg",
            "cloud",
            "arrow-repeat",
            "arrow-down-circle-fill",
            "file-earmark-text",
            "layout-sidebar",
            "arrows-fullscreen",
            "trash3",
            "code-slash",
            "file-diff",
            "table",
        ] {
            let symbol = super::glyph(name);
            assert_ne!(symbol, "?", "unknown icon {name}");
            let id = face
                .glyph_index(symbol.chars().next().unwrap())
                .unwrap_or_else(|| panic!("missing icon {name}"));
            let bounds = face.glyph_bounding_box(id).unwrap();
            assert!(
                bounds.width() > 0 && bounds.height() > 0,
                "empty icon {name}"
            );
        }
    }
}
