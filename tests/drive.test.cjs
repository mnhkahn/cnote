const {test}=require('node:test'),assert=require('node:assert/strict');
const {chromium,webkit}=require('playwright'),html=require('./editor-fixture.cjs')();
for(const [name,type]of [['Chromium',chromium],['WebKit',webkit]])test(name+' OneDrive file manager',async()=>{
 const browser=await type.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1250,height:850}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setContent(`<script>
   window.messages=[];window.fixture=[{id:'folder',name:'Documents',folder:{},eTag:'f1'},{id:'b',name:'b.txt',size:10,eTag:'b1',lastModifiedDateTime:'2026-11-13T10:00:00Z'},{id:'a',name:'a.txt',size:20,eTag:'a1'}];
   window.ipc={postMessage(raw){const m=JSON.parse(raw);messages.push(m);if(m.type==='workspace')cnoteTools.show(m.index);if(m.type==='tool_ready')setTimeout(()=>cnoteTools.receive({type:'tool_state',state:{}}),0);if(m.type!=='drive')return;
    let data={changed:true};if(m.op==='list'||m.op==='search')data={folder:{id:m.parent||'root',folder:{}},items:m.parent==='folder'?[]:fixture};
    if(m.op==='read')data={item:fixture.find(x=>x.id===m.id),text:'original text'};
    if(m.op==='rename')fixture.find(x=>x.id===m.id).name=m.name;
    if(m.op==='download')data={paths:['/Downloads/a.txt'],directory:'/Downloads/OneDrive-test',copy:true};
    if(m.op==='delete')fixture=fixture.filter(x=>x.id!==m.id);
    setTimeout(()=>cnoteDrive.receive({request:m.request,data}),0);
   }};
  </script>`+html);
  await page.evaluate(()=>cnoteDrive.account(true,'Test account'));
  await page.keyboard.press('Meta+6');await page.waitForSelector('#drive-list [data-id="a"]');
  assert.equal(await page.locator('#drive-tool').isVisible(),true);
  assert.equal(await page.locator('#trello-tool').isVisible(),false);
  assert.deepEqual(await page.locator('#drive-list [data-id]').evaluateAll(rows=>rows.map(x=>x.dataset.id)),['folder','a','b']);
  await page.locator('#drive-sort').selectOption('size');
  assert.deepEqual(await page.locator('#drive-list [data-id]').evaluateAll(rows=>rows.map(x=>x.dataset.id)),['folder','b','a']);
  await page.locator('[data-id="folder"]').dblclick();await page.waitForFunction(()=>messages.some(x=>x.op==='list'&&x.parent==='folder'));
  await page.locator('#drive-up').click();await page.waitForSelector('[data-id="a"]');
  await page.locator('[data-id="a"]').click();await page.keyboard.press('Meta+c');
  await page.waitForFunction(()=>messages.some(x=>x.op==='download'));
  assert.deepEqual(await page.evaluate(()=>messages.find(x=>x.op==='download').ids),['a']);
  await page.waitForFunction(()=>document.getElementById('drive-status').textContent.includes('Finder'));
  await page.keyboard.press('Meta+f');await page.locator('#drive-search').fill('a');await page.keyboard.press('Meta+c');
  assert.equal(await page.evaluate(()=>messages.filter(x=>x.op==='download').length),1);
  await page.keyboard.press('Enter');await page.waitForFunction(()=>messages.some(x=>x.op==='search'&&x.query==='a'));
  await page.locator('[data-id="a"]').click();await page.locator('#drive-rename').click();
  await page.locator('#drive-dialog-name').fill('renamed.txt');await page.locator('#drive-dialog-ok').click();
  await page.waitForFunction(()=>messages.some(x=>x.op==='rename'));
  assert.equal(await page.evaluate(()=>messages.find(x=>x.op==='rename').etag),'a1');
  await page.waitForFunction(()=>document.querySelector('[data-id="a"]').textContent.includes('renamed.txt'));
  await page.locator('[data-id="a"]').click();await page.locator('#drive-edit').click();
  await page.waitForSelector('#drive-dialog-text');await page.locator('#drive-dialog-text').fill('updated');await page.locator('#drive-dialog-ok').click();
  await page.waitForFunction(()=>messages.some(x=>x.op==='save'&&x.text==='updated'&&x.etag==='a1'));
  await page.waitForFunction(()=>!document.getElementById('drive-refresh').disabled);
  await page.locator('[data-id="a"]').click();await page.locator('#drive-delete').click();
  assert.equal(await page.evaluate(()=>messages.some(x=>x.op==='delete')),false);
  await page.locator('#drive-dialog button[value="cancel"]').click();
  await page.locator('#drive-delete').click();await page.locator('#drive-dialog-ok').click();
  await page.waitForFunction(()=>!document.querySelector('[data-id="a"]'));
  await page.locator('[data-id="b"]').click();await page.keyboard.press('Meta+a');
  assert.equal(await page.locator('#drive-list [aria-selected="true"]').count(),2);
  await page.locator('#drive-mkdir').click();await page.locator('#drive-dialog-name').fill('新目录');await page.locator('#drive-dialog-ok').click();
  await page.waitForFunction(()=>messages.some(x=>x.op==='mkdir'&&x.parent==='root'&&x.name==='新目录'));
  await page.waitForFunction(()=>!document.getElementById('drive-refresh').disabled);
  await page.locator('[data-id="b"]').click();await page.locator('#drive-move').click();await page.locator('#drive-dialog-name').fill('/Documents');await page.locator('#drive-dialog-ok').click();
  await page.waitForFunction(()=>messages.some(x=>x.op==='move'&&x.destination==='/Documents'&&x.etag==='b1'));
  await page.waitForFunction(()=>!document.getElementById('drive-refresh').disabled);
  await page.locator('#drive-new').click();await page.locator('#drive-dialog-name').fill('empty.txt');await page.locator('#drive-dialog-ok').click();
  await page.waitForFunction(()=>messages.some(x=>x.op==='upload'&&x.name==='empty.txt'&&x.data===''));
  await page.waitForFunction(()=>!document.getElementById('drive-refresh').disabled);
  await page.locator('#drive-files').setInputFiles({name:'upload.txt',mimeType:'text/plain',buffer:Buffer.from('uploaded')});
  await page.waitForFunction(()=>messages.some(x=>x.op==='upload'&&x.name==='upload.txt'&&atob(x.data)==='uploaded'));
  await page.waitForFunction(()=>!document.getElementById('drive-refresh').disabled);
  await page.locator('[data-id="b"]').click();await page.locator('#drive-open').click();
  await page.waitForFunction(()=>messages.some(x=>x.op==='download'&&x.open===true&&x.copy===false));
  await page.screenshot({path:'/tmp/cnote-drive-'+name+'.png'});
  assert.deepEqual(errors,[]);
 }finally{await browser.close();}
});
